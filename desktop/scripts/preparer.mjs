// Prépare ce que l'installateur embarque (dossier build/) :
//   - build/frontend : l'interface construite, qui appelle l'API locale http://127.0.0.1:37100
//   - build/backend  : le backend compilé pour SQLite, les migrations SQLite et ses dépendances de production
// La version serveur reste sur PostgreSQL : le backend est copié dans build/backend-src, où son schéma Prisma est
// converti pour SQLite (voir schema-sqlite.mjs) avant génération du client et compilation. Le dossier backend/
// n'est pas modifié.
// Migrations SQLite : desktop/prisma-sqlite/migrations (à conserver dans git). Si le schéma a changé depuis la
// dernière, une nouvelle migration est créée automatiquement.
// Usage : npm run preparer (puis npm run demarrer pour essayer, ou npm run installateur pour le .exe).
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { schemaSqlite } from './schema-sqlite.mjs';

const desktop = join(dirname(fileURLToPath(import.meta.url)), '..');
const racine = join(desktop, '..');
const backendSource = join(racine, 'backend');
const build = join(desktop, 'build');
const staging = join(build, 'backend-src');
const migrationsSqlite = join(desktop, 'prisma-sqlite', 'migrations');
const lancer = (commande, cwd, env = {}) => {
  console.log(`\n> ${commande}  (${cwd})`);
  return execSync(commande, { cwd, stdio: ['ignore', 'pipe', 'inherit'], env: { ...process.env, ...env } }).toString();
};

rmSync(build, { recursive: true, force: true });
mkdirSync(build, { recursive: true });

// 1. Interface : construite dans build/frontend sans toucher à frontend/dist
console.log(
  lancer(`npx vite build --outDir "${join(build, 'frontend')}" --emptyOutDir`, join(racine, 'frontend'), {
    VITE_API_URL: 'http://127.0.0.1:37100',
  }),
);

// 2. Copie du backend, schéma converti pour SQLite
mkdirSync(staging, { recursive: true });
for (const f of ['src', 'nest-cli.json', 'tsconfig.json', 'tsconfig.build.json', 'package.json']) {
  cpSync(join(backendSource, f), join(staging, f), { recursive: true });
}
rmSync(join(staging, 'src', 'generated'), { recursive: true, force: true });
mkdirSync(join(staging, 'prisma'), { recursive: true });
writeFileSync(join(staging, 'prisma', 'schema.prisma'), schemaSqlite(readFileSync(join(backendSource, 'prisma', 'schema.prisma'), 'utf8')));
writeFileSync(
  join(staging, 'prisma.config.ts'),
  `import { defineConfig } from 'prisma/config';
export default defineConfig({
  schema: 'prisma/schema.prisma',
  migrations: { path: ${JSON.stringify(migrationsSqlite.replace(/\\/g, '/'))} },
  datasource: { url: 'file:./build.db', shadowDatabaseUrl: 'file:./shadow.db' },
});
`,
);
symlinkSync(join(backendSource, 'node_modules'), join(staging, 'node_modules'), 'junction');

// 3. Client Prisma SQLite et compilation
lancer('npx prisma generate', staging);
console.log(lancer('npx nest build', staging));

// 4. Migrations SQLite : init, puis une migration par changement du schéma
mkdirSync(migrationsSqlite, { recursive: true });
// Fichier exigé par « prisma migrate diff --from-migrations » pour connaître le fournisseur
if (!existsSync(join(migrationsSqlite, 'migration_lock.toml'))) {
  writeFileSync(join(migrationsSqlite, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "sqlite"\n');
}
const existantes = readdirSync(migrationsSqlite).filter((d) => existsSync(join(migrationsSqlite, d, 'migration.sql')));
const diff = existantes.length
  ? lancer(`npx prisma migrate diff --from-migrations "${migrationsSqlite}" --to-schema prisma/schema.prisma --script`, staging)
  : lancer('npx prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script', staging);
const sql = diff.replace(/^Loaded Prisma config.*$/m, '').trim();
if (sql && !/^-- This is an empty migration\.?$/m.test(sql)) {
  const nom = `${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}_${existantes.length ? 'maj' : 'init'}`;
  mkdirSync(join(migrationsSqlite, nom));
  writeFileSync(join(migrationsSqlite, nom, 'migration.sql'), `${sql}\n`);
  console.log(`\nNouvelle migration SQLite : ${nom}`);
}

// 5. Backend embarqué : compilation, migrations SQLite, dépendances de production
const backend = join(build, 'backend');
mkdirSync(backend, { recursive: true });
cpSync(join(staging, 'dist'), join(backend, 'dist'), { recursive: true });
cpSync(migrationsSqlite, join(backend, 'migrations'), { recursive: true });
cpSync(join(backendSource, 'package.json'), join(backend, 'package.json'));
cpSync(join(backendSource, 'package-lock.json'), join(backend, 'package-lock.json'));
console.log(lancer('npm ci --omit=dev --ignore-scripts --no-audit --no-fund', backend));
// bcrypt : binaire précompilé (N-API) récupéré par son script d'installation
console.log(lancer('npm rebuild bcrypt', backend));
rmSync(staging, { recursive: true, force: true });

console.log('\nPréparation terminée : build/frontend et build/backend');
